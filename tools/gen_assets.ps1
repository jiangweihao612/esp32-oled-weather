function New-IconSnow {
    $bmp = New-IconBitmap
    $g = Get-IconGraphics $bmp
    $pen = New-Object System.Drawing.Pen ([System.Drawing.Color]::Black), ([single]1.6)
    $pen.StartCap = [System.Drawing.Drawing2D.LineCap]::Round
    $pen.EndCap = [System.Drawing.Drawing2D.LineCap]::Round
    $centers = @(@(8, 26), @(17, 29), @(25, 25))
    foreach ($c in $centers) {
        $cx = $c[0]
        $cy = $c[1]
        for ($i = 0; $i -lt 3; $i++) {
            $a = $i * [Math]::PI / 3
            $dx = [Math]::Cos($a) * 3.2
            $dy = [Math]::Sin($a) * 3.2
            $g.DrawLine($pen, [single]($cx - $dx), [single]($cy - $dy), [single]($cx + $dx), [single]($cy + $dy))
        }
    }
    $pen.Dispose()
    $g.Dispose()
    $cloud = Draw-CloudLayer 2 30 17 5
    Overlay-Cloud $bmp $cloud
    $cloud.Dispose()
    return $bmp
}

