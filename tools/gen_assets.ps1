    $rows = @(@(13, 19), @(21, 26), @(29, 15))
    foreach ($r in $rows) {
        $y = $r[0]
        $xEnd = $r[1]
        $g.DrawLine($pen, [single]4, [single]$y, [single]$xEnd, [single]$y)
        $r2 = 3.6
        $g.DrawArc($pen, [single]($xEnd - $r2), [single]($y - 2 * $r2), [single](2 * $r2), [single](2 * $r2), 90, -220)
    }
    $pen.Dispose()
    $g.Dispose()
