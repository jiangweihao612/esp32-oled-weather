# Generate 16x16 Chinese glyph data and 32x32 weather icons for the OLED project.
# Usage: powershell -ExecutionPolicy Bypass -File gen_assets.ps1 -Task all
Param(
    [ValidateSet("all", "font", "icons")]
    [string]$Task = "all"
)

$ErrorActionPreference = "Stop"
Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.Windows.Forms

if (-not $PSScriptRoot) { $PSScriptRoot = (Get-Location).Path }
$toolsDir = $PSScriptRoot
$projDir = Split-Path -Parent $toolsDir

# ---------------------------------------------------------------- utilities
function Pack-Block([System.Drawing.Bitmap]$bmp) {
    $w = $bmp.Width
    $h = $bmp.Height
    $pages = [int]($h / 8)
    $bytes = New-Object 'byte[]' ($w * $pages)
    for ($x = 0; $x -lt $w; $x++) {
        for ($p = 0; $p -lt $pages; $p++) {
            $b = 0
            for ($bit = 0; $bit -lt 8; $bit++) {
                $c = $bmp.GetPixel($x, $p * 8 + $bit)
                $lum = ($c.R + $c.G + $c.B) / 3
                if ($lum -lt 128) { $b = $b -bor (1 -shl $bit) }
            }
            $bytes[$p * $w + $x] = [byte]$b
        }
    }
    return $bytes
}

function Format-Hex([byte[]]$bytes, [int]$perLine) {
    $lines = @()
    for ($i = 0; $i -lt $bytes.Length; $i += $perLine) {
        $end = [Math]::Min($i + $perLine, $bytes.Length) - 1
        $part = @()
        for ($k = $i; $k -le $end; $k++) {
            $part += ("0x{0:X2}" -f $bytes[$k])
        }
        $lines += ("`t" + ($part -join ",") + ",")
    }
    return $lines
}

function Save-Png([System.Drawing.Bitmap]$bmp, [string]$path, [int]$scale) {
    $out = New-Object System.Drawing.Bitmap ($bmp.Width * $scale), ($bmp.Height * $scale)
    $g = [System.Drawing.Graphics]::FromImage($out)
    $g.Clear([System.Drawing.Color]::White)
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
    $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
    $g.DrawImage($bmp, 0, 0, $out.Width, $out.Height)
    $g.Dispose()
    $out.Save($path, [System.Drawing.Imaging.ImageFormat]::Png)
    $out.Dispose()
}

# ---------------------------------------------------------------- font
function Render-Glyph([string]$ch) {
    $bmp = New-Object System.Drawing.Bitmap 16, 16
    $bmp.SetResolution(96, 96)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::White)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
    $font = New-Object System.Drawing.Font("SimSun", 16, [System.Drawing.GraphicsUnit]::Pixel)
    # GDI (TextRenderer) uses the embedded 16px bitmap strike of SimSun,
    # which gives a crisp full-cell 16x16 glyph. GDI+ would render smaller outlines.
    $flags = [System.Windows.Forms.TextFormatFlags]::NoPadding -bor `
             [System.Windows.Forms.TextFormatFlags]::SingleLine -bor `
             [System.Windows.Forms.TextFormatFlags]::NoPrefix
    [System.Windows.Forms.TextRenderer]::DrawText($g, $ch, $font, (New-Object System.Drawing.Point 0, 0), [System.Drawing.Color]::Black, $flags)
    $g.Dispose()
    $font.Dispose()
    return $bmp
}

function Build-Font {
    $raw = [System.IO.File]::ReadAllText((Join-Path $toolsDir "cn_chars.txt"), [System.Text.Encoding]::UTF8)
    $list = New-Object System.Collections.ArrayList
    foreach ($ch in $raw.ToCharArray()) {
        if ([char]::IsWhiteSpace($ch)) { continue }
        $s = [string]$ch
        if (-not $list.Contains($s)) { [void]$list.Add($s) }
    }

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("`t/* ==== BEGIN AUTO GENERATED GLYPHS (tools/gen_assets.ps1) ==== */")
    foreach ($s in $list) {
        $bmp = Render-Glyph $s
        $bytes = Pack-Block $bmp
        $bmp.Dispose()
        [void]$sb.AppendLine("`t`"$s`",")
        foreach ($line in (Format-Hex $bytes 16)) { [void]$sb.AppendLine($line) }
        [void]$sb.AppendLine("")
    }
    [void]$sb.AppendLine("`t/* ==== END AUTO GENERATED GLYPHS ==== */")
    [System.IO.File]::WriteAllText((Join-Path $toolsDir "cn_glyphs.gen"), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

    # preview sheet decoded straight from the generated bytes
    $cols = 10
    $rows = [Math]::Ceiling($list.Count / $cols)
    $cell = 20
    $sheet = New-Object System.Drawing.Bitmap ($cols * $cell), ($rows * $cell)
    $sg = [System.Drawing.Graphics]::FromImage($sheet)
    $sg.Clear([System.Drawing.Color]::White)
    $idx = 0
    foreach ($s in $list) {
        $bmp = Render-Glyph $s
        $bytes = Pack-Block $bmp
        $bmp.Dispose()
        $cx = ($idx % $cols) * $cell
        $cy = [Math]::Floor($idx / $cols) * $cell
        for ($x = 0; $x -lt 16; $x++) {
            for ($y = 0; $y -lt 16; $y++) {
                $b = $bytes[[int][Math]::Floor($y / 8) * 16 + $x]
                if (($b -band (1 -shl ($y % 8))) -ne 0) {
                    $sg.FillRectangle([System.Drawing.Brushes]::Black, $cx + 2 + $x, $cy + 2 + $y, 1, 1)
                }
            }
        }
        $sg.DrawRectangle([System.Drawing.Pens]::LightGray, $cx, $cy, $cell - 1, $cell - 1)
        $idx++
    }
    $sg.Dispose()
    Save-Png $sheet (Join-Path $toolsDir "preview_glyphs.png") 3
    $sheet.Dispose()
    Write-Output ("font: {0} glyphs" -f $list.Count)
}

# ---------------------------------------------------------------- icons
function New-IconBitmap {
    return (New-Object System.Drawing.Bitmap 32, 32)
}

function Get-IconGraphics([System.Drawing.Bitmap]$bmp) {
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::White)
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    return $g
}

function Draw-Cloud($g, [double]$left, [double]$right, [double]$bottom, [double]$bodyH) {
    $br = [System.Drawing.Brushes]::Black
    $w = $right - $left
    $yBase = $bottom - $bodyH
    $g.FillRectangle($br, [single]$left, [single]$yBase, [single]$w, [single]$bodyH)
    $r1 = $w * 0.21
    $r2 = $w * 0.29
    $r3 = $w * 0.17
    $c1 = $left + $r1 * 1.05
    $c2 = $left + $w * 0.44
    $c3 = $right - $r3 * 1.05
    $g.FillEllipse($br, [single]($c1 - $r1), [single]($yBase - $r1), [single](2 * $r1), [single](2 * $r1))
    $g.FillEllipse($br, [single]($c2 - $r2), [single]($yBase - $r2), [single](2 * $r2), [single](2 * $r2))
    $g.FillEllipse($br, [single]($c3 - $r3), [single]($yBase - $r3), [single](2 * $r3), [single](2 * $r3))
    # keep the flat base joined to the puffs
    $g.FillRectangle($br, [single]$left, [single]($yBase - $bodyH * 0.4), [single]$w, [single]($bodyH * 1.4))
}

function Draw-CloudLayer([double]$left, [double]$right, [double]$bottom, [double]$bodyH) {
    $bmp = New-Object System.Drawing.Bitmap 32, 32
    $g = Get-IconGraphics $bmp
    Draw-Cloud $g $left $right $bottom $bodyH
    $g.Dispose()
    return $bmp
}

# draw cloud with a 1px white halo so it separates from what is behind it
function Overlay-Cloud($target, [System.Drawing.Bitmap]$cloud) {
    $mask = New-Object 'bool[,]' 32, 32
    for ($x = 0; $x -lt 32; $x++) {
        for ($y = 0; $y -lt 32; $y++) {
            $c = $cloud.GetPixel($x, $y)
            if ((($c.R + $c.G + $c.B) / 3) -lt 128) { $mask[$x, $y] = $true }
        }
    }
    for ($x = 0; $x -lt 32; $x++) {
        for ($y = 0; $y -lt 32; $y++) {
            if ($mask[$x, $y]) { continue }
            $near = $false
            for ($dx = -1; $dx -le 1; $dx++) {
                for ($dy = -1; $dy -le 1; $dy++) {
                    $nx = $x + $dx
                    $ny = $y + $dy
                    if ($nx -ge 0 -and $nx -lt 32 -and $ny -ge 0 -and $ny -lt 32) {
                        if ($mask[$nx, $ny]) { $near = $true }
                    }
                }
            }
            if ($near) { $target.SetPixel($x, $y, [System.Drawing.Color]::White) }
        }
    }
    for ($x = 0; $x -lt 32; $x++) {
        for ($y = 0; $y -lt 32; $y++) {
            if ($mask[$x, $y]) { $target.SetPixel($x, $y, [System.Drawing.Color]::Black) }
        }
    }
}

function Draw-Sun($g, [double]$cx, [double]$cy, [double]$r) {
    $g.FillEllipse([System.Drawing.Brushes]::Black, [single]($cx - $r), [single]($cy - $r), [single](2 * $r), [single](2 * $r))
    $pen = New-Object System.Drawing.Pen ([System.Drawing.Color]::Black), ([single]2)
    $pen.StartCap = [System.Drawing.Drawing2D.LineCap]::Round
    $pen.EndCap = [System.Drawing.Drawing2D.LineCap]::Round
    for ($i = 0; $i -lt 8; $i++) {
        $a = $i * [Math]::PI / 4
        $x0 = $cx + [Math]::Cos($a) * ($r + 2.4)
        $y0 = $cy + [Math]::Sin($a) * ($r + 2.4)
        $x1 = $cx + [Math]::Cos($a) * ($r + 5.4)
        $y1 = $cy + [Math]::Sin($a) * ($r + 5.4)
        $g.DrawLine($pen, [single]$x0, [single]$y0, [single]$x1, [single]$y1)
    }
    $pen.Dispose()
}

function New-IconSunny {
    $bmp = New-IconBitmap
