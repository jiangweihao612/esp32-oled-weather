function Build-Icons {
    $defs = @(
        @("Sunny", "sunny", { New-IconSunny }),
        @("Partly", "partly", { New-IconPartly }),
        @("Cloudy", "cloudy", { New-IconCloudy }),
        @("Rain", "rain", { New-IconRain }),
        @("Thunder", "thunder", { New-IconThunder }),
        @("Snow", "snow", { New-IconSnow }),
        @("Fog", "fog", { New-IconFog }),
        @("Dust", "dust", { New-IconDust }),
        @("Wind", "wind", { New-IconWind })
    )

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("/* WeatherIcon.cpp - 32x32 monochrome weather icons, auto generated by tools/gen_assets.ps1 */")
    [void]$sb.AppendLine("#include ""WeatherIcon.h""")
    [void]$sb.AppendLine("")

    $sheet = New-Object System.Drawing.Bitmap (3 * 120), (3 * 120)
    $sg = [System.Drawing.Graphics]::FromImage($sheet)
    $sg.Clear([System.Drawing.Color]::White)
    $sg.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
    $sg.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
    $idx = 0
    foreach ($d in $defs) {
        $bmp = & $d[2]
        $bytes = Pack-Block $bmp
        [void]$sb.AppendLine(("const uint8_t WeatherIcon_{0}[WEATHER_ICON_BYTES] = {{" -f $d[0]))
        foreach ($line in (Format-Hex $bytes 16)) { [void]$sb.AppendLine($line) }
        [void]$sb.AppendLine("};")
        [void]$sb.AppendLine("")
        # preview
        $cx = ($idx % 3) * 120
        $cy = [Math]::Floor($idx / 3) * 120
        $sg.DrawString($d[1], (New-Object System.Drawing.Font("Arial", 10)), [System.Drawing.Brushes]::Gray, [single]($cx + 6), [single]($cy + 4))
        $sg.DrawImage($bmp, $cx + 12, $cy + 22, 96, 96)
        $sg.DrawRectangle([System.Drawing.Pens]::LightGray, $cx, $cy, 119, 119)
        $bmp.Dispose()
        $idx++
    }

    [void]$sb.AppendLine("const uint8_t* const WEATHER_ICONS[ICON_COUNT] = {")
    foreach ($d in $defs) {
        [void]$sb.AppendLine(("    WeatherIcon_{0}," -f $d[0]))
    }
    [void]$sb.AppendLine("};")

    [System.IO.File]::WriteAllText((Join-Path $projDir "WeatherIcon.cpp"), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
    $sg.Dispose()
    $sheet.Save((Join-Path $toolsDir "preview_icons.png"), [System.Drawing.Imaging.ImageFormat]::Png)
    $sheet.Dispose()
    Write-Output ("icons: {0}" -f $defs.Count)
}

